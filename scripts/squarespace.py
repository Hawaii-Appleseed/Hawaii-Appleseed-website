def builder_targets():
    """name -> squarespace-ready output file, for every build_squarespace page."""
    t = {os.path.splitext(src)[0]: src for src, _, _, _ in bs.MARKER_PAGES}
    t.update({"index": "index.html", "home": "index.html",
              "support": "support.html", "ufsm": "ufsm.html"})
    return t


def generic_sources():
    """Existing generic injects that have a rebuildable source next to them."""
    found = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames
                       if d not in (".git", "node_modules", "squarespace-ready")]
        if "squarespace-inject.html" in filenames and "index.html" in filenames:
            found.append(os.path.relpath(os.path.join(dirpath, "index.html"), ROOT))
    return sorted(found)


def pbcopy(path):
    with open(path, "rb") as f:
        data = f.read()
    subprocess.run(["pbcopy"], input=data, check=True)
    return len(data)


