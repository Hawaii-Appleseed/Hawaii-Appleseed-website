// Cloudflare Worker entry: CORS, abuse controls, then handleChat.
//
// Secrets and vars (wrangler secret put / wrangler.toml):
//   ANTHROPIC_API_KEY   required
//   TURNSTILE_SECRET    when set, every /chat call must carry a valid Turnstile token
//   ALLOWED_ORIGINS     comma-separated; defaults to the production site
//   MODEL, EFFORT       optional model and effort overrides
//   PER_MINUTE, PER_DAY per-visitor limits (KV binding RATE required); DAILY_CAP is the
//                       whole-site daily request ceiling
//   DAILY_BUDGET_USD    whole-site daily spend ceiling (default 5), counted from real token usage;
//                       needs the same KV binding. The Console workspace limit stays the hard stop.
//   FALLBACKS           "default" turns on server-side refusal fallback (off by default)
//   FEEDBACK "1"        turn on POST /feedback: a rating (and optional comment) on an answer is saved to KV with the
//                       question, answer and the signed-in email for 90 days, for the team to review (internal pilot)
//   GET /stats, /stats.json   the daily roll-up of counts (stats.js), behind the same gate: no text, no emails
//   REQUIRE_ACCESS "1", ACCESS_TEAM_DOMAIN, ACCESS_AUD   internal pilot: every route needs a valid Cloudflare Access
//                       token and the Worker answers 503 until both are set (access.js). GET / serves the widget.
import Anthropic from "@anthropic-ai/sdk";
import { gate } from "./access.js";
import index from "./index.json" with { type: "json" };
import { DEFAULT_MODEL, handleChat } from "./handler.js";
import { microDollars } from "./pricing.js";
import { chartsPage, readCharts, readDays, record, statsPage } from "./stats.js";
import widgetHtml from "./widget.js"; // generated by build_embed.py (npm run widget)

const DEFAULT_ORIGINS = "https://hiappleseed.org,https://www.hiappleseed.org";
const MAX_BODY = 12_000;

const json = (body, status, extra = {}) =>
  new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json", "cache-control": "no-store", ...extra } });

// The widget page: inline script and style (it is one self-contained file), Google Fonts, same-origin API calls only.
const PAGE_HEADERS = {
  "content-type": "text/html; charset=utf-8",
  "cache-control": "no-store",
  "x-content-type-options": "nosniff",
  "x-frame-options": "DENY",
  "referrer-policy": "no-referrer",
  "content-security-policy":
    "default-src 'none'; script-src 'unsafe-inline' https://challenges.cloudflare.com; style-src 'unsafe-inline' https://fonts.googleapis.com; " +
    "font-src https://fonts.gstatic.com data:; connect-src 'self'; img-src 'self' data:; frame-src https://challenges.cloudflare.com; " +
    "base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
};

function corsHeaders(request, env) {
  const origin = request.headers.get("origin");
  const allowed = (env.ALLOWED_ORIGINS ?? DEFAULT_ORIGINS).split(",").map((s) => s.trim());
  allowed.push(new URL(request.url).origin); // the widget served by this Worker calls it from its own origin
  if (!origin || !allowed.includes(origin)) return null;
  return { "access-control-allow-origin": origin, vary: "origin", "access-control-allow-headers": "content-type", "access-control-allow-methods": "POST, GET, OPTIONS" };
}

async function sha(text) {
  const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return [...new Uint8Array(buf)].slice(0, 8).map((b) => b.toString(16).padStart(2, "0")).join("");
}

async function verifyTurnstile(token, ip, env) {
  if (!token) return false;
  const form = new FormData();
  form.append("secret", env.TURNSTILE_SECRET);
  form.append("response", token);
  if (ip) form.append("remoteip", ip);
  const r = await fetch("https://challenges.cloudflare.com/turnstile/v0/siteverify", { method: "POST", body: form });
  return Boolean((await r.json()).success);
}

/** Count a hit in KV; returns true when the visitor is over `limit`. Approximate by design
 *  (KV is eventually consistent); a Cloudflare rate-limiting rule is the hard backstop. */
async function overLimit(kv, key, limit, ttl) {
  const n = Number((await kv.get(key)) ?? 0) + 1;
  await kv.put(key, String(n), { expirationTtl: ttl });
  return n > limit;
}

const FEEDBACK_TTL = 90 * 24 * 3600;
const clip = (v, n) => (typeof v === "string" ? v.replace(/\s+/g, " ").trim().slice(0, n) : "");

/** A thumbs up or down on one answer. Stores the rated Q&A (and the rater's email) so the team can see what went wrong. */
async function handleFeedback(request, env, cors, who, url) {
  if (env.FEEDBACK !== "1" || !env.RATE) return json({ error: "not_found" }, 404);
  if (!cors) return json({ error: "forbidden" }, 403);
  if (Number(request.headers.get("content-length") ?? 0) > MAX_BODY) return json({ error: "too_large" }, 413, cors);
  let b;
  try { b = await request.json(); } catch { return json({ error: "bad_request" }, 400, cors); }
  const rating = b?.rating === "up" || b?.rating === "down" ? b.rating : null;
  const question = clip(b?.question, 800);
  const answer = clip(b?.answer, 2400);
  if (!rating || !question || !answer) return json({ error: "bad_request" }, 400, cors);

  const ip = request.headers.get("cf-connecting-ip") ?? "";
  const visitor = await sha(`${who.email ?? ip}|${env.RATE_SALT ?? "ha"}`);
  if (await overLimit(env.RATE, `f:${visitor}:${new Date().toISOString().slice(0, 10)}`, Number(env.FEEDBACK_PER_DAY ?? 60), 90000)) {
    return json({ error: "rate_limited" }, 429, cors);
  }
  const now = new Date().toISOString();
  const entry = {
    ts: now, email: who.email, rating, comment: clip(b?.comment, 500), question, answer,
    sources: Array.isArray(b?.sources) ? b.sources.slice(0, 6).map((u) => clip(u, 300)).filter(Boolean) : [],
    model: env.MODEL ?? DEFAULT_MODEL, built: index.built,
  };
  await env.RATE.put(`fb:${now}:${crypto.randomUUID().slice(0, 8)}`, JSON.stringify(entry), { expirationTtl: FEEDBACK_TTL });
  console.log(JSON.stringify({ event: "feedback", rating }));
  await record(env.RATE, { feedback: rating });
  return json({ ok: true }, 200, cors);
}

/** The kept sample of charts the model drew, for a person to read (/stats/charts, /stats/charts.json). */
async function handleCharts(env, url) {
  if (!env.RATE) return json({ error: "not_found" }, 404);
  const charts = await readCharts(env.RATE, 14);
  return url.pathname.endsWith(".json") ? json({ charts }, 200) : new Response(chartsPage(charts), { headers: PAGE_HEADERS });
}

/** The staff usage page (HTML) or its data (/stats.json): counts only. */
async function handleStats(env, url) {
  if (!env.RATE) return json({ error: "not_found" }, 404);
  const n = Math.min(60, Math.max(1, Number(url.searchParams.get("days")) || 14));
  const days = await readDays(env.RATE, n);
  if (url.pathname === "/stats.json") return json({ days, built: index.built }, 200);
  const spentToday = Number((await env.RATE.get(`usd:${new Date().toISOString().slice(0, 10)}`)) ?? 0);
  return new Response(statsPage(days, { budgetUsd: Number(env.DAILY_BUDGET_USD ?? 5), spentToday, built: index.built }), { headers: PAGE_HEADERS });
}

export async function handleRequest(request, env, deps = {}) {
  const url = new URL(request.url);
  // Internal pilot: nothing, not even /health, answers without a verified Access token. Fail closed.
  const who = await gate(request, env, deps.access);
  if (!who.ok) return json({ error: who.error }, who.status);
  if (request.method === "GET" && url.pathname === "/") return new Response(widgetHtml, { headers: PAGE_HEADERS });
  if (request.method === "GET" && (url.pathname === "/stats" || url.pathname === "/stats.json")) return handleStats(env, url);
  if (request.method === "GET" && (url.pathname === "/stats/charts" || url.pathname === "/stats/charts.json")) return handleCharts(env, url);
  if (url.pathname === "/favicon.ico") return new Response(null, { status: 204 });
  const cors = corsHeaders(request, env);
  if (request.method === "OPTIONS") return new Response(null, { status: cors ? 204 : 403, headers: cors ?? {} });
  if (url.pathname === "/health") return json({ ok: true, built: index.built, public: index.public, chunks: index.chunks.length, source: index.source }, 200);
  if (url.pathname === "/feedback" && request.method === "POST") return handleFeedback(request, env, cors, who, url);
  if (url.pathname !== "/chat" || request.method !== "POST") return json({ error: "not_found" }, 404);
  if (!cors) return json({ error: "forbidden" }, 403);

  if (Number(request.headers.get("content-length") ?? 0) > MAX_BODY) return json({ error: "too_large" }, 413, cors);
  let payload;
  try {
    payload = await request.json();
  } catch {
    return json({ error: "bad_request" }, 400, cors);
  }

  const ip = request.headers.get("cf-connecting-ip") ?? "";
  if (env.TURNSTILE_SECRET && !(await verifyTurnstile(payload.turnstileToken, ip, env))) {
    await record(env.RATE, { blocked: "verification_failed" });
    return json({ error: "verification_failed", answer: "Please reload the page and try again." }, 403, cors);
  }
  let newPerson = false; // first request today from this person: for the roll-up's "people" count
  if (env.RATE) {
    const day = new Date().toISOString().slice(0, 10);
    const visitor = await sha(`${who.email ?? ip}|${env.RATE_SALT ?? "ha"}`);
    const tooMany =
      (await overLimit(env.RATE, `m:${visitor}:${Math.floor(Date.now() / 60000)}`, Number(env.PER_MINUTE ?? 8), 120)) ||
      (await overLimit(env.RATE, `d:${visitor}:${day}`, Number(env.PER_DAY ?? 60), 90000)) ||
      (await overLimit(env.RATE, `all:${day}`, Number(env.DAILY_CAP ?? 2000), 90000));
    newPerson = !tooMany && (await env.RATE.get(`d:${visitor}:${day}`)) === "1";
    if (tooMany) {
      await record(env.RATE, { blocked: "rate_limited" });
      return json({ error: "rate_limited", answer: "That's a lot of questions at once. Please try again a little later, or browse hiappleseed.org." }, 429, cors);
    }
  }

  // Daily spend ceiling, counted from the usage each answer reports. Soft by design (KV is not atomic);
  // it stops a busy day, and the Anthropic workspace spend limit is what stops everything.
  const day = new Date().toISOString().slice(0, 10);
  const budgetKey = `usd:${day}`;
  const budget = Number(env.DAILY_BUDGET_USD ?? 5) * 1e6;
  const spent = env.RATE ? Number((await env.RATE.get(budgetKey)) ?? 0) : 0;
  if (env.RATE && spent >= budget) {
    console.log(JSON.stringify({ event: "budget_reached", spentUsd: spent / 1e6 }));
    await record(env.RATE, { blocked: "budget" });
    return json({ error: "budget", answer: "The assistant has reached its limit for today. Please try again tomorrow, or browse hiappleseed.org.", sources: [], related: [] }, 429, cors);
  }

  const client = deps.client ?? new Anthropic({ apiKey: env.ANTHROPIC_API_KEY });
  const { status, body, usage, model, meta } = await handleChat({ messages: payload.messages, index, client, env });
  if (env.RATE && usage) {
    await env.RATE.put(budgetKey, String(spent + microDollars(usage, model ?? env.MODEL ?? DEFAULT_MODEL)), { expirationTtl: 90000 });
  }
  await record(env.RATE, meta?.route === "bad_request" ? { blocked: "bad_request", newPerson } : { ...meta, usage, model: model ?? env.MODEL ?? DEFAULT_MODEL, newPerson });
  return json(body, status, cors);
}

export default { fetch: (request, env) => handleRequest(request, env) };
