#!/usr/bin/env python3
"""Build the widget into ONE self-contained file to paste into a Squarespace Code Block.

index.html links the website's design tokens (assets/tokens.css) and the ʻokina fonts (assets/okina.css). This
inlines both, so the output needs nothing from the website repo or its GitHub Pages host, and works from a
standalone chatbot repo (vendor.py copies the two CSS files into vendor/assets/).

    python3 chatbot/build_embed.py                                  # -> chatbot/dist/embed.html
    python3 chatbot/build_embed.py --endpoint https://ha-ask.<acct>.workers.dev/chat --sitekey 0x4AAA...

It does what scripts/squarespace.py does for a standalone page, and the output is ASCII-only because Squarespace
mangles raw UTF-8 in code blocks. In the website repo you can still publish through scripts/squarespace.py
(it builds chatbot/squarespace-inject.html); use this file when chatbot/ lives in its own repo.
"""
from __future__ import annotations

import argparse
import html as htmllib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# What Squarespace needs on narrow screens: it pads a Code Block's column, so the widget breaks out to full width.
BREAKOUT = """<style>
@media (max-width:1080px){
  #%(id)s{
    width: 100vw !important;
    max-width: 100vw !important;
    margin-left: calc(50%% - 50vw) !important;
    margin-right: calc(50%% - 50vw) !important;
  }
}
</style>"""


def find_assets() -> Path:
    for cand in (HERE / "vendor" / "assets", HERE.parent / "assets"):
        if (cand / "tokens.css").exists() and (cand / "okina.css").exists():
            return cand
    raise SystemExit("tokens.css / okina.css not found: run python3 chatbot/vendor.py (or build inside the website repo)")


def asciify_css(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)  # comments are where the non-ASCII lives
    css = re.sub(r"\n\s*\n+", "\n", css).strip()
    bad = [c for c in css if ord(c) > 127]
    if bad:
        raise SystemExit(f"non-ASCII left in CSS after stripping comments: {sorted(set(bad))}")
    return css


def asciify_js(js: str) -> str:
    return "".join(c if ord(c) < 128 else f"\\u{ord(c):04X}" for c in js)


def build(endpoint: str = "", sitekey: str = "", notice: str = "") -> str:
    src = (HERE / "index.html").read_text(encoding="utf-8")
    assets = find_assets()
    head, _, rest = src.partition("<body")
    body = rest.split(">", 1)[1].rsplit("</body>", 1)[0].strip()
    body = re.sub(r"^(\s*<!--.*?-->)+", "", body, flags=re.S).strip()  # a leading comment is not content
    m = re.match(r'<div id="([^"]+)"', body)
    if not m:
        raise SystemExit("index.html body must be a single wrapper <div id=...>")
    wrapper = m.group(1)

    fonts = [ln.strip() for ln in head.splitlines() if "fonts.googleapis" in ln or "fonts.gstatic" in ln]
    okina = asciify_css((assets / "okina.css").read_text(encoding="utf-8"))
    tokens = asciify_css((assets / "tokens.css").read_text(encoding="utf-8"))

    if endpoint:
        body = body.replace('data-endpoint=""', f'data-endpoint="{endpoint}"', 1)
    if sitekey:
        body = body.replace('data-turnstile-sitekey=""', f'data-turnstile-sitekey="{sitekey}"', 1)
    if notice:  # a banner at the top of the widget, e.g. for a staff-only pilot
        body, n = re.subn(r'(<section class="ha-ask"[^>]*>)', lambda m: m.group(1) + f'\n  <p class="ha-ask__notice" role="note">{htmllib.escape(notice)}</p>', body, count=1)
        if n != 1:
            raise SystemExit('index.html has no <section class="ha-ask"> to put the notice in')

    # Non-ASCII safety, segment by segment: JS gets \uXXXX escapes, CSS must already be clean, HTML gets entities.
    parts = re.split(r"(<script>.*?</script>|<style>.*?</style>)", body, flags=re.S)
    out = []
    for p in parts:
        if p.startswith("<script>"):
            out.append(asciify_js(p))
        elif p.startswith("<style>"):
            out.append(p.replace(p[7:-8], asciify_css(p[7:-8]), 1))
        else:
            out.append(p.encode("ascii", "xmlcharrefreplace").decode("ascii"))
    body = "".join(out)

    return (
        "<!-- GENERATED by chatbot/build_embed.py from chatbot/index.html: do not hand-edit.\n"
        "     Paste into a Squarespace Code Block. Self-contained: the design tokens and okina fonts are inlined. -->\n"
        + "\n".join(fonts)
        + f"\n<style>\n{okina}\n</style>\n<style>\n{tokens}\n</style>\n"
        + BREAKOUT % {"id": wrapper}
        + "\n"
        + body
        + "\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--endpoint", default="", help="the Worker's /chat URL, written into data-endpoint")
    ap.add_argument("--sitekey", default="", help="Cloudflare Turnstile site key, written into data-turnstile-sitekey")
    ap.add_argument("--notice", default="", help="a banner shown above the widget, e.g. for a staff-only pilot")
    ap.add_argument("--worker-module", type=Path, help="also write the page as a JS module (export default \"...\") for the Worker to serve")
    ap.add_argument("--out", type=Path, default=HERE / "dist" / "embed.html")
    a = ap.parse_args()
    html = build(a.endpoint, a.sitekey, a.notice)
    assert all(ord(c) < 128 for c in html), "output must be ASCII"
    a.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = a.out.with_suffix(".html.tmp")
    tmp.write_text(html, encoding="utf-8")
    tmp.replace(a.out)
    if a.worker_module:
        a.worker_module.parent.mkdir(parents=True, exist_ok=True)
        a.worker_module.write_text("// GENERATED by chatbot/build_embed.py (npm run widget): do not edit.\nexport default " + json.dumps(html) + ";\n", encoding="utf-8")
        print(f"wrote {a.worker_module} (Worker module)")
    print(f"wrote {a.out}  {len(html)/1000:.1f} KB, self-contained"
          + (f", endpoint {a.endpoint}" if a.endpoint else ", no endpoint set (preview only)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
